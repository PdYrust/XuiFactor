func TestRebindPostgresPlaceholders(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{"no placeholders", "SELECT 1", "SELECT 1"},
		{"two placeholders", "SELECT * FROM t WHERE a = ? AND b = ?", "SELECT * FROM t WHERE a = $1 AND b = $2"},
		{"question mark in string literal", "SELECT 'a?b', ? FROM t", "SELECT 'a?b', $1 FROM t"},
		{"escaped quote in string literal", "SELECT 'it''s ?', ? FROM t", "SELECT 'it''s ?', $1 FROM t"},
		{"placeholder before literal", "UPDATE t SET a = ? WHERE b = 'x?'", "UPDATE t SET a = $1 WHERE b = 'x?'"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := rebindPostgres(tc.in); got != tc.want {
				t.Fatalf("rebind %q = %q, want %q", tc.in, got, tc.want)
			}
		})
	}
}

func TestMigrationStatementsUseDialectIdentityColumn(t *testing.T) {
	sqliteStatements := migrationStatements(DriverSQLite)
	postgresStatements := migrationStatements(DriverPostgres)
	if len(sqliteStatements) != len(postgresStatements) || len(sqliteStatements) != len(migrationTableStatements) {
		t.Fatalf("unexpected statement counts: sqlite=%d postgres=%d base=%d",
			len(sqliteStatements), len(postgresStatements), len(migrationTableStatements))
	}
	for _, statement := range sqliteStatements {
		if strings.Contains(statement, migrationIDPlaceholder) {
			t.Fatalf("sqlite statement still contains the identity placeholder: %s", statement)
		}
		if strings.Contains(statement, "GENERATED BY DEFAULT AS IDENTITY") {
			t.Fatalf("sqlite statement contains the postgres identity column: %s", statement)
		}
	}
	for _, statement := range postgresStatements {
		if strings.Contains(statement, migrationIDPlaceholder) {
			t.Fatalf("postgres statement still contains the identity placeholder: %s", statement)
		}
		if strings.Contains(statement, "AUTOINCREMENT") {
			t.Fatalf("postgres statement contains SQLite AUTOINCREMENT: %s", statement)
		}
	}
}
